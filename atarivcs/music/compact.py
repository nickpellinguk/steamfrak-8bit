#!/usr/bin/env python3
"""
The tune in a compact form for musicdrv_c.asm: reads frakmusic.inc (build_music.py's output, for
musicdrv.asm) and writes frakmusic_c.inc. Nothing about the sound changes (equiv_test.py checks the
two drivers' register writes frame by frame); only the encoding:

  * one byte per note: bits 0-5 the code, bits 6-7 its length (8, 16, 24 or 32 frames). Longer
    notes are split into ties (code 61), which carry on without a new attack; three or more in a
    row become code 60 and a byte, their total frames. End of a channel's stream: 62 (back to its
    loop point).
  * both channels share one note table: a byte per pitch, AUDF in bits 0-4 and bit 7 set for
    AUDC 4 (clear: AUDC 12); the bass's notes first, then the lead's. Codes: notes 0-, slides
    from SLIDE0, 61 tie, 62 end, 63 rest.
  * one slide table; each channel one stream (its patterns, each played once, in order) and a loop
    point (MusLoopLo / Hi).

    python3 atarivcs/music/compact.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LENS = (8, 16, 24, 32)


def parse(path):
    src = open(path).read()
    tabs = {}
    for name, body in re.findall(r'^(\w+):\s*\.byte\s+([^\n]+)', src, re.M):
        tabs[name] = [v.strip() for v in body.split(',')]
    consts = dict(re.findall(r'^(\w+)\s*=\s*(\d+)', src, re.M))
    labels = re.findall(r'^(\w+):', src, re.M)
    return src, tabs, consts, labels


def num(v):
    return int(v.replace('$', '0x'), 0)


def main():
    src, tabs, consts, labels = parse(os.path.join(HERE, 'frakmusic.inc'))
    out = ['; GENERATED by atarivcs/music/compact.py from frakmusic.inc: the compact form for',
           '; musicdrv_c.asm (one byte per note; see compact.py)']
    notes, base = [], {}
    for ch in ('Bass', 'Lead'):
        base[ch] = len(notes)
        for c, f in zip(tabs[ch + 'C'], tabs[ch + 'F']):
            c, f = num(c), num(f)
            assert c in (12, 4) and f < 32, (ch, c, f)
            notes.append(f | (0x80 if c == 4 else 0))
    # slides: each channel's slide sequences, pitch indexes made global
    slides, slide_ofs = [], []
    for ch in ('Bass', 'Lead'):
        seqs = sorted((int(n[len(ch) + 2:]), n) for n in tabs if re.fullmatch(ch + r'Sl\d+', n))
        ids = {}
        for i, n in seqs:
            ids[i] = len(slide_ofs)
            start = len(slides)
            seq = tabs[n]
            k = 0
            while k < len(seq):
                v = seq[k]
                if v == '$FF':
                    slides.append(0xFF)
                elif v == '$FE':            # loop back: the offset that follows is a label difference
                    raise SystemExit('looping slides are not handled yet')
                else:
                    slides.append(num(v) + base[ch])
                k += 1
            slide_ofs.append(start)
        base[ch + 'Slides'] = ids
    slide0 = len(notes)
    assert slide0 + len(slide_ofs) <= 61, 'too many notes and slides for 6-bit codes'
    # patterns
    pats, pat_of = [], {}
    for ch in ('Bass', 'Lead'):
        for n in sorted((int(n[len(ch) + 3:]), n) for n in tabs if re.fullmatch(ch + r'Pat\d+', n)):
            vals = [num(v) for v in tabs[n[1]]]
            body, k = [], 0
            while vals[k] != 62:
                code, length = vals[k], vals[k + 1]
                k += 2
                if code < 48:
                    code += base[ch]
                elif code < 61:
                    code = slide0 + base[ch + 'Slides'][code - 48]
                assert length % 8 == 0 and length > 0, (n, length)
                first = True
                while length:
                    piece = min(length, 32)
                    if length - piece and length - piece < 8:
                        piece -= 8
                    body.append((code if first else 61) | (LENS.index(piece) << 6))
                    first, length = False, length - piece
            body.append(62)
            pat_of[(ch, n[0])] = len(pats)
            pats.append(body)
    # each channel as one stream: its patterns in order (each is played once, in order), the end
    # markers dropped, one 62 at the stream's end (back to its loop point); chains of three or more
    # 32-frame ties become code 60 and a frame count (up to 255)
    streams, loopofs = [], []
    for ch in ('Bass', 'Lead'):
        idx = [pat_of[(ch, num(v))] for v in tabs[ch + 'Order'] if v != '$FF']
        loop = int(consts[ch + 'Loop'])
        body, lofs = [], 0
        for k, pi in enumerate(idx):
            if k == loop:
                lofs = len(body)
                body.append(None)                # (a barrier: no tie chain crosses the loop point)
            body += pats[pi][:-1]
        out_b, k = [], 0
        while k < len(body):
            v = body[k]
            if v is None:
                lofs = len(out_b)
                k += 1
                continue
            run = 0
            while k + run < len(body) and body[k + run] is not None and body[k + run] & 0x3F == 61:
                run += 1
            if run >= 3:
                frames = 0
                n = 0
                while n < run and frames + LENS[body[k + n] >> 6] <= 255:
                    frames += LENS[body[k + n] >> 6]
                    n += 1
                if n >= 3:
                    out_b += [60, frames]
                    k += n
                    continue
            out_b.append(v)
            k += 1
        streams.append(out_b + [62])
        loopofs.append(lofs)
    out.append('SLIDE0 = %d' % slide0)
    out.append('MusNote: .byte ' + ','.join(str(v) for v in notes))
    out.append('MusSlide: .byte ' + ','.join(str(v) for v in slide_ofs))
    for k in range(0, len(slides), 32):
        out.append(('MusSlides: .byte ' if k == 0 else '        .byte ') + ','.join('$%02X' % v for v in slides[k:k + 32]))
    out.append('MusLoopLo: .byte <(MusBass+%d),<(MusLead+%d)' % tuple(loopofs))
    out.append('MusLoopHi: .byte >(MusBass+%d),>(MusLead+%d)' % tuple(loopofs))
    for name, st in zip(('MusBass', 'MusLead'), streams):
        for k in range(0, len(st), 32):
            out.append(('%s: .byte ' % name if k == 0 else '        .byte ') + ','.join(str(v) for v in st[k:k + 32]))
    open(os.path.join(HERE, 'frakmusic_c.inc'), 'w').write('\n'.join(out) + '\n')
    size = len(notes) + len(slide_ofs) + len(slides) + 4 + sum(map(len, streams))
    print('frakmusic_c.inc: %d bytes of data (streams %d)' % (size, sum(map(len, streams))))


if __name__ == '__main__':
    main()
