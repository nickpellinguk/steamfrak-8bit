#!/usr/bin/env python3
"""Compress the front end (attract screen and menus) for frak.ssd.

The front end is assembled to run at &8000 in bank 7, where the level's unrolled
background goes while a level is played. It's kept compressed in the emptier
sprite bank and unpacked into bank 7 (by fe_unpack) each time the menus come up.

    pack.py PASS1_SSD

reads FRONT from the first-pass disc image, then writes build/FRONT.lz,
src/gen/packed.asm (its size and address) and the address into src/gen/boot.txt.

The format (byte-aligned LZ77, decoded by fe_unpack in src/frak.asm):
    0                    the end
    1-127      n         n literal bytes follow
    &80-&FF    n         copy (n AND &7F) + 2 bytes from earlier in the output, at a
                         distance given by the next byte d (d < &80: distance d + 1)
                         or the next two (d >= &80: distance ((d AND &7F) * 256 + e) + 1)
"""
import os
import re
import sys

MAX_LIT = 127
MIN_MATCH, MAX_MATCH = 2, 129
MAX_DIST = 0x8000
STAGE_SIZE = 64             # room left below the data for fe_stage


def read_ssd(path, wanted):
    d = open(path, 'rb').read()
    count = d[0x105] // 8
    for i in range(count):
        name = d[8 + i * 8: 15 + i * 8].decode('latin-1').rstrip()
        info = d[0x108 + i * 8: 0x110 + i * 8]
        if name == wanted:
            length = info[4] | info[5] << 8 | ((info[6] >> 4) & 3) << 16
            sector = info[7] | (info[6] & 3) << 8
            return d[sector * 256: sector * 256 + length]
    raise SystemExit('%s not found in %s' % (wanted, path))


def compress(data):
    n = len(data)
    # the longest match at each position, with a distance under 128 and with any distance
    chains = {}
    best_short = [0] * n
    best_long = [(0, 0)] * n
    best_short_dist = [0] * n
    for i in range(n):
        key = bytes(data[i:i + 2])
        cands = chains.get(key, [])
        bs = bl = 0
        bsd = bld = 0
        for j in reversed(cands):
            dist = i - j
            if dist > MAX_DIST:
                break
            l = 0
            while l < MAX_MATCH and i + l < n and data[j + l] == data[i + l]:
                l += 1
            if dist <= 128 and l > bs:
                bs, bsd = l, dist
            if l > bl:
                bl, bld = l, dist
            if bl == MAX_MATCH:
                break
        best_short[i], best_short_dist[i] = bs, bsd
        best_long[i] = (bl, bld)
        chains.setdefault(key, []).append(i)

    # cheapest encoding from each position to the end
    INF = 1 << 30
    cost = [INF] * (n + 1)
    choice = [None] * (n + 1)
    cost[n] = 1                                 # (the end marker)
    for i in range(n - 1, -1, -1):
        for l in range(1, min(MAX_LIT, n - i) + 1):
            c = 1 + l + cost[i + l]
            if c < cost[i]:
                cost[i], choice[i] = c, ('lit', l)
        for l in range(MIN_MATCH, best_short[i] + 1):
            c = 2 + cost[i + l]
            if c < cost[i]:
                cost[i], choice[i] = c, ('copy', l, best_short_dist[i])
        bl, bld = best_long[i]
        for l in range(MIN_MATCH, bl + 1):
            c = 3 + cost[i + l]
            if c < cost[i]:
                cost[i], choice[i] = c, ('copy', l, bld)

    out = bytearray()
    i = 0
    while i < n:
        ch = choice[i]
        if ch[0] == 'lit':
            out.append(ch[1])
            out += data[i:i + ch[1]]
            i += ch[1]
        else:
            _, l, dist = ch
            out.append(0x80 | (l - 2))
            d = dist - 1
            if d < 0x80:
                out.append(d)
            else:
                out += bytes([0x80 | d >> 8, d & 0xFF])
            i += l
    out.append(0)
    return bytes(out)


def decompress(packed):
    out = bytearray()
    i = 0
    while True:
        c = packed[i]; i += 1
        if c == 0:
            return bytes(out)
        if c < 0x80:
            out += packed[i:i + c]; i += c
        else:
            d = packed[i]; i += 1
            if d >= 0x80:
                d = (d & 0x7F) << 8 | packed[i]; i += 1
            for _ in range((c & 0x7F) + 2):
                out.append(out[-d - 1])


def main():
    front = read_ssd(sys.argv[1], 'FRONT')
    packed = compress(front)
    assert decompress(packed) == front
    open('build/FRONT.lz', 'wb').write(packed)
    consts = open('src/gen/consts.asm').read()
    top = int(re.search(r'SLOWSAVE0_START = &(\w+)', consts).group(1), 16)
    org = top - len(packed) - STAGE_SIZE
    open('src/gen/packed.asm', 'w').write(
        '\\ The packed front end - GENERATED by tools/pack.py, do not edit\n'
        'FRONTZ_ORG = &%04X\nFRONT_SIZE = %d\nFRONTZ_SIZE = %d\n' % (org, len(front), len(packed)))
    boot = open('src/gen/boot.txt').read().replace('FRONTZ_ORG', '%X' % org)
    boot = re.sub(r'(\*SRLOAD FRONTZ )\w+', r'\g<1>%X' % org, boot)
    open('src/gen/boot.txt', 'w').write(boot)
    print('Front end: %d bytes, packed to %d (%d%%)' % (len(front), len(packed), 100 * len(packed) // len(front)))


if __name__ == '__main__':
    main()
