# music_a8.py: the music for the Atari (src/sound.asm): the BBC version's tunes, instruments and
# envelopes (../tools/music.py, from the Steam version's: as the C64 and CPC versions use them),
# translated from BeebAsm for 64tass, and the POKEY's own tables: each 1/8 semitone's clock count
# in one octave (the 1.79MHz clock's half-periods, times 4, at pitch 0: 100Hz; shifted right an
# octave at a time), the BBC chip's noise rates as dividers of the 64kHz clock, and the BBC
# chip's 2dB loudness steps as the POKEY's volumes. Writes build/music.inc.
import math, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); B = os.path.join(HERE, '..', 'build')
SF = os.environ.get('STEAMFRAK') or os.path.join(HERE, '..', '..', '..', 'steamfrak')
gen = os.path.join(B, 'mgen'); os.makedirs(gen, exist_ok=True)
subprocess.run([sys.executable, os.path.join(HERE, '..', '..', 'tools', 'music.py'), SF, gen], check=True, capture_output=True)
out = ['; GENERATED by tools/music_a8.py from ../tools/music.py\'s (BeebAsm, translated)']
for f in ('music_main.asm', 'music.asm'):
    for l in open(os.path.join(gen, f)):
        l = l.rstrip('\n')
        l = re.sub(r'^\\', ';', l)
        l = re.sub(r'^\.(\w+)', r'\1', l)
        l = l.replace('EQUB', '.byte').replace('EQUW', '.word')
        l = re.sub(r'\bLO\(', '<(', l); l = re.sub(r'\bHI\(', '>(', l)
        out.append(l)
CLK = 1773447                       # (PAL: the 1.79MHz clock)
t16 = [int(round(4 * CLK / 2 / (100.0 * 2 ** (r / 96.0)))) for r in range(96)]
assert max(t16) < 65536
out += ['; the POKEY\'s: clock counts (1.79MHz half-periods x 4) for one octave of 1/8 semitones from 100Hz',
        'pt16_lo .byte ' + ', '.join(str(v & 255) for v in t16), 'pt16_hi .byte ' + ', '.join(str(v >> 8) for v in t16),
        '; the BBC chip\'s noise rates (4MHz / 512, 1024, 2048: its noise register\'s low 2 bits; 3, tone 2\'s, as 2) as',
        '; dividers of the 64kHz clock (its 17-bit noise clocked at 63337 / (N + 1))',
        'pnoise  .byte ' + ', '.join(str(int(round(CLK / 28 / r)) - 1) for r in (4e6 / 512, 4e6 / 1024, 4e6 / 2048, 4e6 / 2048)),
        '; the BBC chip\'s attenuation (2dB steps, 15 off) as the POKEY\'s volume (0-15, linear)',
        'pvol    .byte ' + ', '.join(str(0 if a == 15 else max(1, int(round(15 * 10 ** (-2 * a / 20))))) for a in range(16))]
t = '\n'.join(out)                  # (the BBC chip's dividers: not wanted)
t = re.sub(r'(?m)^ntab_(lo|hi)\n(\s+\.byte.*\n)+', '', t + '\n')
open(os.path.join(B, 'music.inc'), 'w').write(t)
print('music: build/music.inc')
