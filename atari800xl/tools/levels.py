# levels.py: the levels the program carries (A_1, A_2, A_3: the front end's 1, 2, 3), as the C64
# port's lvldata.mjs and loader do: each level's own tables and numbers (build/<level>_geom.json,
# _screen.json: geom.py's and screen.py's) at fixed places in a block (each table as long as the
# longest level's; the gems and keys 12 long, the enemies 9, the patch objects 21), so the code is
# the same for any; each level's block packed, with its character set and map (the BBC version's
# packer), for the program to unpack the chosen one's at the start (levelset: the block to LVL,
# the set to FONTA, the map to the screen's). The patch objects' cells (4 bytes each: row, column,
# the code gone, there) follow the
# tables, each object's pointer (pkpl, pkph) in LVL's place. Writes build/levels.inc and
# build/lv_<level>.lz, lvf_<level>.lz.
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); B = os.path.join(HERE, '..', 'build')
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
from pack import compress, decompress

def packto(data, path):             # (packed with the BBC version's packer; unchanged data's kept: packing's slow)
    data = bytes(data)
    if os.path.exists(path) and os.path.exists(path + '.src') and open(path + '.src', 'rb').read() == data: return open(path, 'rb').read()
    z = compress(data); assert decompress(z) == data
    open(path, 'wb').write(z); open(path + '.src', 'wb').write(data)
    return z
LEVELS = ['A_1', 'A_2', 'A_3']
ORIGA = 0xac00                       # (LVL's block ends before it)
NP, NS, NO = 12, 9, 21
FIXED = {**{k: NP for k in ('pkll', 'pklh', 'pkrl', 'pkrh', 'pkt', 'pkb', 'pkkey', 'pkxl', 'pkxh', 'pkpd', 'pkil', 'pkih', 'pkit', 'pkh')},
         **{k: NS for k in ('scr_xl', 'scr_xh', 'scr_pd', 'scrT', 'scrB', 'scbll', 'scblh', 'scbrl', 'scbrh', 'scbt', 'scbb', 'scil', 'scih', 'scit')},
         'pkn': NO}
lv = []
for L in LEVELS:
    g, s = json.load(open(os.path.join(B, f'{L}_geom.json'))), json.load(open(os.path.join(B, f'{L}_screen.json')))
    lv.append({'T': {**g['T'], **s['T']}, 'S': {**g['S'], **s['S']}, 'cells': s['cells']})
# (worked out at the start, lvderive: so not packed, after everything that is)
DERIVED = ['pcol', 'plist', 'lcol', 'llist', 'pkll', 'pklh', 'pkrl', 'pkrh', 'pkt', 'pkb', 'pkxl', 'pkxh', 'pkpd',
           'scbll', 'scblh', 'scbrl', 'scbrh', 'scbt', 'scbb', 'scr_xl', 'scr_xh', 'scr_pd', 'scrT', 'scrB']
snames = list(lv[0]['S'])
tnames = [n for n in lv[0]['T'] if n not in DERIVED]
size = lambda n: FIXED.get(n) or max(1, max(len(l['T'][n]) for l in lv))
at, off = {}, 0
for n in snames: at[n] = off; off += len(lv[0]['S'][n])
for n in tnames: at[n] = off; off += size(n)
at['pkpl'] = off; off += NO
at['pkph'] = off; off += NO
at['pkc'] = off; off += max(sum(len(c) for c in l['cells']) for l in lv)    # (4 bytes a cell: packed as 3, spread out)
for n in DERIVED: at[n] = off; off += size(n) + (1 if n in ('pcol', 'lcol') else 0)
LVLSIZE = off
LVL = ORIGA - LVLSIZE
inc = ['; GENERATED by tools/levels.py: the levels\' blocks (unpacked at the start: levelset)', f'LVL = ${LVL:04x}', f'LVLSIZE = {LVLSIZE}', f'NP = {NP}', f'NS = {NS}', f'NPO = {NO}']
inc += [f'{n:10s}= LVL + {at[n]}' for n in snames + tnames + ['pkpl', 'pkph', 'pkc'] + DERIVED]
report = []
for i, (L, l) in enumerate(zip(LEVELS, lv)):
    b = bytearray(LVLSIZE)
    for n in snames: b[at[n]:at[n] + len(l['S'][n])] = bytes(l['S'][n])
    for n in tnames:
        v = l['T'][n]; assert len(v) <= size(n), (L, n)
        b[at[n]:at[n] + len(v)] = bytes(v)
    p, c3 = LVL + at['pkc'], bytearray()
    for k, c in enumerate(l['cells']):
        b[at['pkpl'] + k], b[at['pkph'] + k] = p & 255, p >> 8
        c3 += bytes(v for i, v in enumerate(c) if i % 4 != 3)        # (row, column, gone: there's the map's)
        p += len(c)
    b[at['pkc']:at['pkc'] + len(c3)] = c3
    b = b[:at['pkc'] + len(c3)]                                      # (packed: up to the cells' end)
    for nm, data in ((f'lv_{L}.lz', bytes(b)), (f'lvf_{L}.lz', open(os.path.join(B, f'{L}_font.bin'), 'rb').read())):
        z = packto(data, os.path.join(B, nm))
        report.append(f'{nm} {len(z)}')
    inc += ([f'      .if LVCOUNT > {i}'] if i else []) + [f'lvb{i}    .binary "../build/lv_{L}.lz"', f'lvf{i}    .binary "../build/lvf_{L}.lz"',
            f'lvm{i}    .binary "../build/{L}_map.lz"'] + (['      .endif'] if i else [])
inc.append('      .if LVCOUNT > 1')             # (LVCOUNT: the levels the program carries, trogg8x4.asm's)
for nm in ('lvb', 'lvf', 'lvm'):
    inc += [f'{nm}lo   .byte ' + ', '.join(f'<{nm}{i}' for i in range(len(LEVELS))), f'{nm}hi   .byte ' + ', '.join(f'>{nm}{i}' for i in range(len(LEVELS)))]
inc.append('      .else')
for nm in ('lvb', 'lvf', 'lvm'):
    inc += [f'{nm}lo   .byte <{nm}0', f'{nm}hi   .byte >{nm}0']
inc.append('      .endif')
for L in LEVELS:
    codes = len(open(os.path.join(B, f'{L}_font.bin'), 'rb').read().rstrip(bytes(1))) // 8 + 1
    assert codes <= 64, f'{L}: its glyphs reach the spare characters (64 on)'
open(os.path.join(B, 'levels.inc'), 'w').write('\n'.join(inc) + '\n')
json.dump({'levels': LEVELS}, open(os.path.join(B, 'levels.json'), 'w'))
print(f'levels: block {LVLSIZE} bytes at ${LVL:04x}; packed: ' + ', '.join(report))
