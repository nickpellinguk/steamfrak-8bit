#!/usr/bin/env python3
"""
The CPC version's graphics, from the BBC version's converter (tools/convert.py, which the
build runs first): every coded sprite and the code tables are in its sideways RAM bank 4
(build/GFX4, 16K at &8000), which becomes the CPC's extra bank 0 at &4000, unchanged.
So this only rebases the image directory.

Reads (in the repository's root):  build/GFX4, src/gen/sprites.asm, src/gen/imgdir.asm,
                                   src/gen/imgdir3.asm
Writes (in cpc6128/):              build/GFX (the bank), src/gen/images.asm (the image
                                   directory, for RASM), build/images.json (for the tests)

Image directory, per image: img_w, img_h, img_xo, img_yo, and for each shift s (0-3) img_lo<s>,
img_hi<s> (its data's address) and img_bank<s> (CODED, or 0 if the image has no data at that
shift); img_svl/img_svh, the most a save record of it can take (see plot.asm).
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CPC = os.path.dirname(HERE)
ROOT = os.path.dirname(CPC)
CODED = 0x80
SAVE_HEADER = 2


def asm_tables(path):
    """{label: [values]} from BeebAsm EQUB tables (a value that isn't a number reads as None)"""
    tables, consts, label = {}, {}, None
    for line in open(path):
        line = line.strip()
        m = re.match(r'^\.(\w+)$', line)
        if m:
            label = m.group(1)
            tables[label] = []
            continue
        m = re.match(r'^(\w+)\s*=\s*(\d+)$', line)
        if m:
            consts[m.group(1)] = int(m.group(2))
            continue
        if line.startswith('EQUB') and label:
            for v in line[4:].split(','):
                v = v.strip()
                tables[label].append(int(v[1:], 16) if v.startswith('&') else int(v) if v.isdigit() else None)
    return tables, consts


def main():
    gfx = open(os.path.join(ROOT, 'build', 'GFX4'), 'rb').read()
    sprites, consts = asm_tables(os.path.join(ROOT, 'src', 'gen', 'sprites.asm'))
    dirs = {}
    for name in ('imgdir.asm', 'imgdir3.asm'):
        dirs.update(asm_tables(os.path.join(ROOT, 'src', 'gen', name))[0])
    n = consts['NUM_IMAGES']
    names = {v: k for k, v in consts.items() if k.startswith('IMG_')}
    images = []
    for i in range(n):
        im = {'name': names.get(i, str(i)), 'w': sprites['img_w'][i], 'h': sprites['img_h'][i],
              'xo': sprites['img_xo'][i], 'yo': sprites['img_yo'][i], 'shift': {}}
        for s in range(4):
            bank, lo, hi = dirs['img_bank%d' % s][i], dirs['img_lo%d' % s][i], dirs['img_hi%d' % s][i]
            if bank and bank & CODED and lo is not None and hi is not None:
                # (only coded images, all in bank 4; the HUD timer, drawn into RAM, comes later)
                im['shift'][s] = (lo | hi << 8) - 0x8000 + 0x4000
        wb = max([(s + im['w'] + 3) // 4 for s in im['shift']] or [0])
        im['save'] = SAVE_HEADER + wb * (2 + im['h']) if im['shift'] else 0
        images.append(im)
    os.makedirs(os.path.join(CPC, 'build'), exist_ok=True)
    os.makedirs(os.path.join(CPC, 'src', 'gen'), exist_ok=True)
    open(os.path.join(CPC, 'build', 'GFX'), 'wb').write(gfx)
    json.dump({'images': images, 'code_tables': 0x7C00}, open(os.path.join(CPC, 'build', 'images.json'), 'w'))

    def table(label, values):
        out = [label]
        for k in range(0, len(values), 16):
            out.append('        db ' + ', '.join('#%02X' % v for v in values[k:k + 16]))
        return out
    out = ['; Image directory - GENERATED by tools/gfx.py, do not edit', '',
           'NUM_IMAGES = %d' % n, 'CODED = #%02X' % CODED,
           'CODE_LPIX = #7C00', 'CODE_LMASK = #7D00', 'CODE_RPIX = #7E00', 'CODE_RMASK = #7F00']
    out += ['%s = %d' % (names[i], i) for i in sorted(names)]
    out.append('')
    for field in ('w', 'h', 'xo', 'yo'):
        out += table('img_' + field, [im[field] for im in images])
    for s in range(4):
        # (in this order: plot finds img_hi<s> and img_bank<s> NUM_IMAGES and 2 * NUM_IMAGES on)
        out += table('img_lo%d' % s, [im['shift'].get(s, 0) & 255 for im in images])
        out += table('img_hi%d' % s, [im['shift'].get(s, 0) >> 8 for im in images])
        out += table('img_bank%d' % s, [CODED if s in im['shift'] else 0 for im in images])
    out += table('img_svl', [im['save'] & 255 for im in images])
    out += table('img_svh', [im['save'] >> 8 for im in images])
    open(os.path.join(CPC, 'src', 'gen', 'images.asm'), 'w').write('\n'.join(out) + '\n')
    print('%d images, %d bytes of sprites and tables' % (n, len(gfx)))


if __name__ == '__main__':
    main()
