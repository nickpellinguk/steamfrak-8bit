#!/usr/bin/env python3
"""
The CPC version's graphics, from the BBC version's converter (tools/convert.py, which the
build runs first): every coded sprite and the code tables are in its sideways RAM bank 4
(build/GFX4, 16K at &8000), which becomes the CPC's extra bank 0 at &4000, unchanged.
So this only rebases the image directory.

Reads (in the repository's root):  build/GFX4, build/PACK, build/SPANS, src/gen/sprites.asm,
                                   src/gen/imgdir.asm, src/gen/imgdir3.asm, src/gen/collide.asm,
                                   src/gen/levels.asm, src/gen/consts.asm, src/gen/music_main.asm
Writes (in cpc6128/):              build/GFX (the bank), build/PACK (the levels), src/gen/images.asm
                                   (the image directory, for RASM), src/gen/levels.asm (where each
                                   level is, the meanies' settings, the converter's constants),
                                   build/images.json (for the tests), build/SPANS and
                                   src/gen/collide.asm (the collision data), src/gen/sounds.asm

The levels: the BBC version's PACK (12K: its HAZEL segment, then ANDY's two) is loaded at &4000
in the base RAM as it is, so a level at BBC address a is at &4000 + (a - &C000) if a is in
HAZEL, else &6000 + (a - &8000).

Image directory, per image: img_w, img_h, img_xo, img_yo, and for each shift s (0-3) img_lo<s>,
img_hi<s> (its data's address) and img_bank<s> (CODED, or 0 if the image has no data at that
shift); img_svl/img_svh, the most a save record of it can take (see plot.asm).
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CPC = os.path.dirname(HERE)
ROOT = os.path.dirname(CPC)
CODED = 0x80
SAVE_HEADER = 2
LINE_SAVE = 24                     # (plot.asm's: the yoyo string's save record)
BBC_SPANS_ORG = 0x8010             # (where the BBC version has its spans, in bank 6)
CPC_SPANS_ORG = 0x4000             # (and where the CPC version has them, in extra bank 2)


def asm_tables(path):
    """{label: [values]} from BeebAsm EQUB tables (a value that isn't a number reads as None)"""
    tables, consts, label = {}, {}, None
    for line in open(path):
        line = line.strip()
        m = re.match(r'^\.(\w+)$', line)
        if m:
            label = m.group(1)
            tables[label] = []
            continue
        m = re.match(r'^(\w+)\s*=\s*(\d+)$', line)
        if m:
            consts[m.group(1)] = int(m.group(2))
            continue
        if line.startswith('EQUB') and label:
            for v in line[4:].split(','):
                v = v.strip()
                tables[label].append(int(v[1:], 16) if v.startswith('&') else int(v) if v.isdigit() else None)
    return tables, consts


def main():
    gfx = open(os.path.join(ROOT, 'build', 'GFX4'), 'rb').read()
    sprites, consts = asm_tables(os.path.join(ROOT, 'src', 'gen', 'sprites.asm'))
    dirs = {}
    for name in ('imgdir.asm', 'imgdir3.asm'):
        dirs.update(asm_tables(os.path.join(ROOT, 'src', 'gen', name))[0])
    n = consts['NUM_IMAGES']
    names = {v: k for k, v in consts.items() if k.startswith('IMG_')}
    images = []
    for i in range(n):
        im = {'name': names.get(i, str(i)), 'w': sprites['img_w'][i], 'h': sprites['img_h'][i],
              'xo': sprites['img_xo'][i], 'yo': sprites['img_yo'][i], 'shift': {}}
        for s in range(4):
            bank, lo, hi = dirs['img_bank%d' % s][i], dirs['img_lo%d' % s][i], dirs['img_hi%d' % s][i]
            if bank and bank & CODED and lo is not None and hi is not None:
                # (only coded images, all in bank 4; the HUD timer, drawn into RAM, comes later)
                im['shift'][s] = (lo | hi << 8) - 0x8000 + 0x4000
        wb = max([(s + im['w'] + 3) // 4 for s in im['shift']] or [0])
        im['save'] = SAVE_HEADER + wb * (2 + im['h']) if im['shift'] else 0
        images.append(im)
    os.makedirs(os.path.join(CPC, 'build'), exist_ok=True)
    os.makedirs(os.path.join(CPC, 'src', 'gen'), exist_ok=True)
    open(os.path.join(CPC, 'build', 'GFX'), 'wb').write(gfx)
    json.dump({'images': images, 'code_tables': 0x7C00}, open(os.path.join(CPC, 'build', 'images.json'), 'w'))

    def table(label, values):
        out = [label]
        for k in range(0, len(values), 16):
            out.append('        db ' + ', '.join('#%02X' % v for v in values[k:k + 16]))
        return out
    out = ['; Image directory - GENERATED by tools/gfx.py, do not edit', '',
           'NUM_IMAGES = %d' % n, 'CODED = #%02X' % CODED,
           'CODE_LPIX = #7C00', 'CODE_LMASK = #7D00', 'CODE_RPIX = #7E00', 'CODE_RMASK = #7F00']
    out += ['%s = %d' % (names[i], i) for i in sorted(names)]
    out.append('')
    for field in ('w', 'h', 'xo', 'yo'):
        out += table('img_' + field, [im[field] for im in images])
    for s in range(4):
        # (in this order: plot finds img_hi<s> and img_bank<s> NUM_IMAGES and 2 * NUM_IMAGES on)
        out += table('img_lo%d' % s, [im['shift'].get(s, 0) & 255 for im in images])
        out += table('img_hi%d' % s, [im['shift'].get(s, 0) >> 8 for im in images])
        out += table('img_bank%d' % s, [CODED if s in im['shift'] else 0 for im in images])
    kinds = asm_tables(os.path.join(ROOT, 'src', 'gen', 'collide.asm'))[0]['img_kind']
    out += table('img_kind', kinds[:n])
    out += table('img_svl', [im['save'] & 255 for im in images])
    out += table('img_svh', [im['save'] >> 8 for im in images])
    open(os.path.join(CPC, 'src', 'gen', 'images.asm'), 'w').write('\n'.join(out) + '\n')
    print('%d images, %d bytes of sprites and tables' % (n, len(gfx)))

    # ---- the levels
    pack = open(os.path.join(ROOT, 'build', 'PACK'), 'rb').read()
    open(os.path.join(CPC, 'build', 'PACK'), 'wb').write(pack)
    lev, _ = asm_tables(os.path.join(ROOT, 'src', 'gen', 'levels.asm'))
    where = [lo | hi << 8 for lo, hi in zip(lev['level_addr_lo'], lev['level_addr_hi'])]
    where = [0x4000 + a - 0xC000 if a >= 0xC000 else 0x6000 + a - 0x8000 for a in where]
    out = ['; Levels - GENERATED by tools/gfx.py, do not edit', '',
           'PACK_ORG = #4000', 'PACK_SIZE = #%04X' % len(pack)]
    for line in open(os.path.join(ROOT, 'src', 'gen', 'consts.asm')):
        m = re.match(r'^(NUM_LEVELS|START_LEVEL|MAX_\w+|SL_\w+|KIND_\w+|LADDER_EXTRA_LENGTH|HOOTER_PEAK)\s*=\s*(\d+)', line)
        if m:
            out.append('%s = %s' % (m.group(1), m.group(2)))
    out.append('')
    out += table('level_addr_lo', [a & 255 for a in where])
    out += table('level_addr_hi', [a >> 8 for a in where])
    for k in ('slp_kind', 'slp_vf', 'slp_vi', 'slp_wait', 'slp_flags', 'slp_ymin', 'slp_ymax'):
        out += table(k, [v & 255 for v in lev[k]])
    open(os.path.join(CPC, 'src', 'gen', 'levels.asm'), 'w').write('\n'.join(out) + '\n')
    print('%d levels, %d bytes' % (len(where), len(pack)))

    # ---- the collision data: the BBC version's spans (its bank 6, at SPANS_ORG) go at the start
    # of the CPC's logic bank (extra bank 2, at #4000)
    spans = open(os.path.join(ROOT, 'build', 'SPANS'), 'rb').read()
    open(os.path.join(CPC, 'build', 'SPANS'), 'wb').write(spans)
    col, _ = asm_tables(os.path.join(ROOT, 'src', 'gen', 'collide.asm'))
    addrs = [lo | hi << 8 for lo, hi in zip(col['img_span_lo'][:n], col['img_span_hi'][:n])]
    addrs = [a - BBC_SPANS_ORG + CPC_SPANS_ORG for a in addrs]
    out = ['; Collision tables - GENERATED by tools/gfx.py, do not edit', '',
           'SPANS_ORG = #%04X' % CPC_SPANS_ORG, 'SPANS_SIZE = %d' % len(spans), '']
    for k in ('img_bx0', 'img_bx1', 'img_by0', 'img_by1'):
        out += table(k, col[k][:n])
    out += table('img_span_lo', [a & 255 for a in addrs])
    out += table('img_span_hi', [a >> 8 for a in addrs])
    # Trogg's images: each is drawn as two (body and legs: part b 255 if just one), and the
    # save area keeps room for him, the yoyo and its string, and the FRAK! bubble
    pa, pb = col['img_part_a'][:n], col['img_part_b'][:n]
    out += table('img_part_a', pa) + table('img_part_b', pb)
    sv = lambda i: images[i]['save'] if i != 255 else 0
    trogg = [i for i in range(n) if images[i]['name'].startswith('IMG_Trogg_')]
    yoyo = [i for i in range(n) if images[i]['name'].startswith('IMG_Yoyo_')]
    frak = [i for i in range(n) if images[i]['name'] == 'IMG_Frak'][0]
    alive = max(sv(pa[i]) + sv(pb[i]) for i in trogg) + max(sv(i) for i in yoyo) + LINE_SAVE
    out += ['SAVE_RESERVE_ALIVE = %d' % alive, 'SAVE_RESERVE_DEAD = %d' % (alive + sv(frak))]
    open(os.path.join(CPC, 'src', 'gen', 'collide.asm'), 'w').write('\n'.join(out) + '\n')
    # ... and the sound effects' and tunes' numbers
    out = ['; Sound numbers - GENERATED by tools/gfx.py, do not edit', '']
    for line in open(os.path.join(ROOT, 'src', 'gen', 'music_main.asm')):
        m = re.match(r'^((?:TUNE|SFX)_\w+|NUM_TUNES|NUM_SFX)\s*=\s*(\d+)', line)
        if m:
            out.append('%s = %s' % (m.group(1), m.group(2)))
    out.append('SFX_STOP = #7F')
    open(os.path.join(CPC, 'src', 'gen', 'sounds.asm'), 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
